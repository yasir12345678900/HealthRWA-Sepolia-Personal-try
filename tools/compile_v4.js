// Build the JSON artefacts of the thesis-design contracts, so that the Python client and the tests need no Node.
//   TC=<toolchain dir> node tools/compile_v4.js          (run from the repository root)
// <toolchain dir>/node_modules must hold solc 0.8.24, @openzeppelin/contracts 4.9.6 and circomlibjs 0.1.7.
// Without TC the script looks in tools/node_modules, as tools/compile_sol.js does.
// Output, all in blockchain/abi/:
//   ConsentSBTv4.json, ConsentDecisionVerifier.json, MockDecisionVerifier.json   solc 0.8.24, optimizer 200
//   PoseidonT3.json            the Poseidon contract for two inputs, bytecode from circomlibjs poseidonContract
//   ConsentTreeVectors.json    Poseidon values and tree roots computed off chain with circomlibjs, for the tests
//   HalahDecisionVerifier.json only when contracts/HalahDecisionVerifier.sol (the exported Groth16 verifier) exists
const fs = require("fs"), path = require("path"), crypto = require("crypto");
const NM = path.resolve(process.env.TC || process.argv[2] || "tools", "node_modules");
const solc = require(path.join(NM, "solc")), circomlibjs = require(path.join(NM, "circomlibjs"));
const version = name => JSON.parse(fs.readFileSync(path.join(NM, name, "package.json"), "utf8")).version;
const OUT = path.join("blockchain", "abi");
const FIELD = 21888242871839275222246405745257275088548364400416034343698204186575808495617n;
const DEPTH = 16;

const findImports = p => { const f = path.join(NM, p); return fs.existsSync(f) ? { contents: fs.readFileSync(f, "utf8") } : { error: "not found " + p }; };

// Compile one source file and write the artefact of one of its contracts.
function compile(file, name, outName, extra) {
  const input = { language: "Solidity", sources: { [path.basename(file)]: { content: fs.readFileSync(file, "utf8") } },
    settings: { optimizer: { enabled: true, runs: 200 }, outputSelection: { "*": { "*": ["abi", "evm.bytecode.object", "storageLayout"] } } } };
  const res = JSON.parse(solc.compile(JSON.stringify(input), { import: findImports }));
  const errs = (res.errors || []).filter(e => e.severity === "error");
  if (errs.length) { console.error(errs.map(e => e.formattedMessage).join("\n")); process.exit(1); }
  const c = res.contracts[path.basename(file)][name];
  const art = { contractName: outName || name, compiler: "solc " + version("solc") + " optimizer 200", abi: c.abi, bytecode: "0x" + c.evm.bytecode.object };
  // the state variables in storage order and the fields of the structs, so that a test can show what the contract is able to store
  if (extra && extra.storage) {
    const types = c.storageLayout.types;
    art.storage = c.storageLayout.storage.map(v => ({ label: v.label, slot: v.slot, offset: v.offset, type: types[v.type].label }));
    art.structs = Object.fromEntries(Object.values(types).filter(t => t.members).map(t => [t.label, t.members.map(m => ({ label: m.label, type: types[m.type].label }))]));
  }
  fs.writeFileSync(path.join(OUT, (outName || name) + ".json"), JSON.stringify(art, null, 1));
  console.log("COMPILED", outName || name, "| functions:", c.abi.filter(x => x.type === "function").length, "| bytecode bytes:", c.evm.bytecode.object.length / 2);
}

// A field element that depends only on its label, for the test vectors.
const element = label => BigInt("0x" + crypto.createHash("sha256").update(label).digest("hex")) % FIELD;

(async () => {
  const poseidon = await circomlibjs.buildPoseidon();
  const H = (l, r) => poseidon.F.toObject(poseidon([l, r]));

  // Roots of the empty subtrees. The constants of ConsentSBTv4._zero must be exactly these values.
  const zeros = [0n];
  for (let h = 0; h < DEPTH; h++) zeros.push(H(zeros[h], zeros[h]));
  const sbt = fs.readFileSync(path.join("contracts", "ConsentSBTv4.sol"), "utf8");
  for (let h = 1; h <= DEPTH; h++) {
    const line = "if (height == " + h + ") return 0x" + zeros[h].toString(16).padStart(64, "0") + ";";
    if (!sbt.includes(line)) { console.error("ConsentSBTv4._zero(" + h + ") differs from circomlibjs, expected: " + line); process.exit(1); }
  }

  compile(path.join("contracts", "ConsentSBTv4.sol"), "ConsentSBTv4", null, { storage: true });
  compile(path.join("contracts", "ConsentDecisionVerifier.sol"), "ConsentDecisionVerifier");
  compile(path.join("contracts", "MockDecisionVerifier.sol"), "MockDecisionVerifier");
  const exported = path.join("contracts", "HalahDecisionVerifier.sol");
  if (fs.existsSync(exported)) compile(exported, "Groth16Verifier", "HalahDecisionVerifier");

  // The Poseidon contract: its bytecode is generated by circomlibjs, not compiled from Solidity.
  const source = "circomlibjs " + version("circomlibjs") + " poseidonContract.createCode(2)";
  fs.writeFileSync(path.join(OUT, "PoseidonT3.json"), JSON.stringify({ contractName: "PoseidonT3", compiler: source,
    abi: circomlibjs.poseidonContract.generateABI(2), bytecode: circomlibjs.poseidonContract.createCode(2) }, null, 1));
  console.log("GENERATED PoseidonT3 |", source);

  // Test vectors. The tree is recomputed from its leaves for every step, top down over the occupied part only,
  // which is a different method from the incremental updates of the contract.
  const root = (leaves, h, i) => {                       // node i at height h over the sparse map index -> leaf
    if (h === 0) return leaves.get(i) || 0n;
    const lo = BigInt(i) << BigInt(h), hi = lo + (1n << BigInt(h));
    let occupied = false;
    for (const k of leaves.keys()) if (BigInt(k) >= lo && BigInt(k) < hi) { occupied = true; break; }
    return occupied ? H(root(leaves, h - 1, 2 * i), root(leaves, h - 1, 2 * i + 1)) : zeros[h];
  };
  const pairs = [[0n, 0n], [1n, 2n], [2n, 1n], [FIELD - 1n, FIELD - 1n], [element("left"), element("right")]];
  const consent = new Map(), revoked = new Map(), sequence = [];
  const step = entry => sequence.push({ ...entry, consentRoot: root(consent, DEPTH, 0).toString(), revocationRoot: root(revoked, DEPTH, 0).toString() });
  const mint = () => { const c = element("halah consent " + consent.size); consent.set(consent.size, c); step({ op: "mint", tokenId: consent.size, commitment: c.toString() }); };
  const revoke = tokenId => { revoked.set(tokenId - 1, 1n); step({ op: "revoke", tokenId }); };
  // 20 mints with 7 revocations between them: neighbouring leaves, both orders, the first and the newest leaf
  for (let i = 0; i < 5; i++) mint();
  revoke(2); revoke(1);
  for (let i = 0; i < 4; i++) mint();
  revoke(9); revoke(4);
  for (let i = 0; i < 8; i++) mint();
  revoke(17); revoke(16);
  for (let i = 0; i < 3; i++) mint();
  revoke(20);
  fs.writeFileSync(path.join(OUT, "ConsentTreeVectors.json"), JSON.stringify({
    source: "circomlibjs " + version("circomlibjs") + " buildPoseidon, computed off chain by tools/compile_v4.js",
    field: FIELD.toString(), depth: DEPTH,
    poseidon: pairs.map(([l, r]) => ({ inputs: [l.toString(), r.toString()], output: H(l, r).toString() })),
    zeros: zeros.map(z => z.toString()), sequence }, null, 1));
  console.log("GENERATED ConsentTreeVectors | steps:", sequence.length);
})();
